// 스마트 가격 및 세금 계산기 (PRD 3.3 로직)

export interface 계산기입력값 {
  도매원가: number;
  수수료율: number; // e.g. 5.5% (스마트스토어), 10.8% (쿠팡), 1.5% (오프라인 카드)
  배송비: number; // 온라인 판매 시 판매자 부담 배송비 (기본 0 또는 3000)
  목표마진율: number; // e.g. 40%
  종합소득세율: number; // e.g. 15% (1400만~5000만 구간 15%, 지방소득세 1.5% 포함 시 16.5%)
  세금계산서발행여부: boolean; // 도매 사입 시 세금계산서/현금영수증 수취 여부 (매입세액 공제)
}

export interface 계산결과 {
  적정판매가: number;
  마지노선판매가: number; // 최대 할인가 (손익분기점)
  
  // 판매가 기준 분석 (적정판매가 적용 시)
  공급가액: number;
  매출부가세: number;
  매입부가세공제: number;
  실납부부가세: number;
  플랫폼수수료: number;
  예상종합소득세: number;
  실제예상순이익: number;
  실제순익률: number;
}

/**
 * 주어진 판매가에 대한 상세 세금 및 마진 분석
 */
export function 판매가_정밀분석(판매가: number, 입력: 계산기입력값) {
  const { 도매원가, 수수료율, 배송비, 종합소득세율, 세금계산서발행여부 } = 입력;
  
  // 1. 부가세 계산 (소비자가격은 부가세 포함)
  const 공급가액 = Math.round(판매가 / 1.1);
  const 매출부가세 = 판매가 - 공급가액;
  
  // 도매 매입세액 공제: 도매 원가에 10% 부가세가 포함되어 적격증빙을 받았다고 가정하거나 공제
  const 매입공급가 = 세금계산서발행여부 ? Math.round(도매원가 / 1.1) : 도매원가;
  const 매입부가세공제 = 세금계산서발행여부 ? (도매원가 - 매입공급가) : 0;
  const 실납부부가세 = Math.max(0, 매출부가세 - 매입부가세공제);

  // 2. 플랫폼 수수료 (판매가 기준)
  const 플랫폼수수료 = Math.round(판매가 * (수수료율 / 100));

  // 3. 과세 전 영업이익 = 판매가 - 도매원가 - 플랫폼수수료 - 배송비 - 실납부부가세
  const 영업이익 = 판매가 - 도매원가 - 플랫폼수수료 - 배송비 - 실납부부가세;

  // 4. 종합소득세 (영업이익이 양수일 때만 부과)
  const 예상종합소득세 = 영업이익 > 0 ? Math.round(영업이익 * (종합소득세율 / 100)) : 0;

  // 5. 최종 실제 순수익
  const 실제예상순이익 = 영업이익 - 예상종합소득세;
  const 실제순익률 = 판매가 > 0 ? Number(((실제예상순이익 / 판매가) * 100).toFixed(1)) : 0;

  return {
    판매가,
    공급가액,
    매출부가세,
    매입부가세공제,
    실납부부가세,
    플랫폼수수료,
    영업이익,
    예상종합소득세,
    실제예상순이익,
    실제순익률,
  };
}

/**
 * 목표 마진율을 만족하는 '적정판매가' 및 손해 보지 않는 '마지노선 판매가' 자동 산출
 */
export function 스마트가격계산(입력: 계산기입력값): 계산결과 {
  const { 도매원가, 수수료율, 배송비, 목표마진율, 종합소득세율 } = 입력;

  if (도매원가 <= 0) {
    return {
      적정판매가: 0,
      마지노선판매가: 0,
      공급가액: 0,
      매출부가세: 0,
      매입부가세공제: 0,
      실납부부가세: 0,
      플랫폼수수료: 0,
      예상종합소득세: 0,
      실제예상순이익: 0,
      실제순익률: 0,
    };
  }

  // 1. 손익분기점 (마지노선 판매가) 탐색
  // 순이익 >= 0 이 되는 최소 판매가
  let minPrice = 도매원가;
  let maxPrice = 도매원가 * 5;
  let 마지노선판매가 = 도매원가;

  for (let p = 도매원가; p <= maxPrice; p += 100) {
    const res = 판매가_정밀분석(p, 입력);
    if (res.실제예상순이익 >= 0) {
      마지노선판매가 = p;
      break;
    }
  }

  // 2. 목표 순마진율(목표마진율 %)을 달성하는 적정판매가 탐색
  // 대략 원가의 1.5배 ~ 4배 사이에서 100원 단위로 계산
  let 적정판매가 = Math.round(도매원가 * 1.8 / 100) * 100; // 기본값
  for (let p = 마지노선판매가; p <= 도매원가 * 5; p += 100) {
    const res = 판매가_정밀분석(p, 입력);
    if (res.실제순익률 >= 목표마진율) {
      적정판매가 = p;
      break;
    }
  }

  // 100원 단위 절상 (의류 소매가 관행: 보통 900원, 000원 단위지만 100원 단위 깔끔하게)
  적정판매가 = Math.ceil(적정판매가 / 100) * 100;
  마지노선판매가 = Math.ceil(마지노선판매가 / 100) * 100;

  const 적정가분석 = 판매가_정밀분석(적정판매가, 입력);

  return {
    적정판매가,
    마지노선판매가,
    공급가액: 적정가분석.공급가액,
    매출부가세: 적정가분석.매출부가세,
    매입부가세공제: 적정가분석.매입부가세공제,
    실납부부가세: 적정가분석.실납부부가세,
    플랫폼수수료: 적정가분석.플랫폼수수료,
    예상종합소득세: 적정가분석.예상종합소득세,
    실제예상순이익: 적정가분석.실제예상순이익,
    실제순익률: 적정가분석.실제순익률,
  };
}
